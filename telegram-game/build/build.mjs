// Builds the widget: inlines the game logic, minifies, checks Telegram's size limits,
// and writes dist/widget.html plus a module the Edge Function imports.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { minify } from 'terser';

const root = new URL('..', import.meta.url).pathname;
const MAX_RAW = 32768;
const MAX_PACKED = 4096;

const source = readFileSync(root + 'widget/widget.html', 'utf8');
const game = readFileSync(root + 'widget/game.js', 'utf8').replace(/^export /gm, '');

const match = /<script>([\s\S]*)<\/script>/.exec(source);
if (!match || !match[1].includes('/*GAME*/')) throw new Error('widget.html must contain a <script> with a /*GAME*/ placeholder');

const { code } = await minify(match[1].replace('/*GAME*/', () => game), {
  ecma: 2020,
  toplevel: true,
  compress: { passes: 3, unsafe_arrows: true, unsafe_math: true },
  mangle: { toplevel: true },
  format: { comments: false },
});

const markup = source.slice(0, match.index)
  .replace(/\s*\n\s*/g, '')
  .replace(/\s*([{};:,])\s*/g, '$1')
  .replace(/;}/g, '}');

const html = `${markup}<script>${code}</script>`;
const raw = Buffer.byteLength(html);
const packed = deflateSync(Buffer.from(html), { level: 9 }).length;
console.log(`widget: ${raw} bytes, ${packed} bytes after zlib-9 (limits ${MAX_RAW} / ${MAX_PACKED})`);
if (html.includes('\0')) throw new Error('the widget must not contain NUL');
if (raw > MAX_RAW || packed > MAX_PACKED) {
  console.error('The widget is over the Telegram size limit.');
  process.exit(1);
}

const hash = createHash('sha256').update(html).digest('hex').slice(0, 12);
mkdirSync(root + 'dist', { recursive: true });
writeFileSync(root + 'dist/widget.html', html);
writeFileSync(
  root + 'supabase/functions/portal-game/widget.generated.ts',
  `// Generated by build/build.mjs. Do not edit.\nexport const HTML = ${JSON.stringify(html)};\nexport const HTML_HASH = ${JSON.stringify(hash)};\n`,
);
